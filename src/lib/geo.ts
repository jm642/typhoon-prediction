/**
 * 地理坐标工具
 *
 * CMA 接口的经度是 0~360° 记法（跨日期变更线 >180°），高德地图与陆海掩膜
 * 都按 -180~180 处理，故在数据归一化入口统一转换（见 src/api/typhoon.ts）。
 */

/** 归一化经度到 [-180, 180)；本就在范围内时原样返回，避免浮点误差（如 159.9 → 159.89999…） */
export function normLng(lng: number): number {
  if (lng >= -180 && lng <= 180) return lng
  return (((lng + 180) % 360) + 360) % 360 - 180
}
